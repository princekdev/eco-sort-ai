export function classifyWaste(input) {
  if (!input || input.trim() === '') return null;

  const query = input.toLowerCase().trim();

  // Direct match against database keys
  for (const [key, data] of Object.entries(WASTE_DATABASE)) {
    if (query.includes(key) || key.includes(query)) {
      return { ...data, matched: true, query: input };
    }
  }

  // Fuzzy keyword match
  for (const [category, keywords] of Object.entries(KEYWORD_MAP)) {
    for (const keyword of keywords) {
      if (query.includes(keyword)) {
        return {
          ...CATEGORY_DEFAULTS[category],
          name: input,
          matched: true,
          fuzzy: true,
          query: input,
        };
      }
    }
  }

  // Not found
  return {
    name: input,
    category: 'Unknown',
    categoryKey: 'unknown',
    icon: '❓',
    action: 'Check Local Guidelines',
    actionColor: 'gray',
    recyclability: null,
    suggestedAction: null,
    sustainabilityTip: null,
    environmentalNote: null,
    sdg: null,
    caution: null,
    matched: false,
    query: input,
  };
}

